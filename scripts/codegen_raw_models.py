SHARED_VIEW_CONTENT = GENERATED_HEADER + textwrap.dedent("""\
    \"\"\"Raw permissive KbnRaw* view models for kb_dashboard_core shared types.\"\"\"

    from typing import ClassVar, TypeVar

    from pydantic import BaseModel as PydanticBaseModel
    from pydantic import ConfigDict, Field, RootModel

    from kb_dashboard_core.shared.view import OmitIfNone, RootDict  # re-export for generated modules

    __all__ = ['BaseRawVwModel', 'OmitIfNone', 'RootDict', 'KbnRawReference']

    T = TypeVar('T')


    class BaseRawVwModel(PydanticBaseModel):
        \"\"\"Permissive base for raw Kibana view models — extra fields are ignored, strict mode off.\"\"\"

        model_config: ClassVar[ConfigDict] = ConfigDict(
            strict=False,
            extra='ignore',
            frozen=False,
            populate_by_name=True,
            use_enum_values=True,
        )


    class KbnRawReference(BaseRawVwModel):
        \"\"\"Represents a reference object in the Kibana JSON structure.\"\"\"

        type: str = Field(default='')
        \"\"\"The type of the referenced object, e.g., 'index-pattern', 'visualization', 'dashboard'.\"\"\"

        id: str = Field(default='')
        \"\"\"The unique or friendly identifier of the referenced object.\"\"\"

        name: str = Field(default='')
        \"\"\"A sometimes namespaced identifier for the reference.\"\"\"
""")


def _write_shared_view(out_dir: Path, all_kbn_names: set[str]) -> None:  # noqa: ARG001
    """Write a manually-crafted shared/view.py for the kbn_raw_models package."""
    shared_dir = out_dir / 'shared'
    shared_dir.mkdir(parents=True, exist_ok=True)
    _write_init(shared_dir / '__init__.py')
    (shared_dir / 'view.py').write_text(SHARED_VIEW_CONTENT)


def _out_path(src_path: Path) -> Path:
    """Map source view.py → output .py path."""
    rel = src_path.relative_to(CORE_SRC)
    return OUT_DIR / rel


def _write_init(path: Path) -> None:
    """Ensure __init__.py exists at path (only if it doesn't already)."""
    if not path.exists():
        path.write_text(GENERATED_HEADER + '\n')


def main() -> None:
    """Generate all KbnRaw* model files."""
    all_kbn_names = collect_all_kbn_names()
    print(f'Discovered {len(all_kbn_names)} Kbn* classes across kb_dashboard_core')

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    generated: list[Path] = []
    # Write the shared/view.py manually — it has special types (TypeVar, RootModel)
    # that the codegen cannot handle generically.
    _write_shared_view(OUT_DIR, all_kbn_names)

    for src_path in sorted(CORE_SRC.rglob('view.py')):
        if src_path.parent.name == 'shared':
            continue  # Handled manually above

        source = src_path.read_text()
        code = _transform_source(source, src_path, all_kbn_names)
        if len(code) == 0:
            continue

        out = _out_path(src_path)
        out.parent.mkdir(parents=True, exist_ok=True)

        # Ensure __init__.py exists at every package level between OUT_DIR and out.parent.
        pkg_dir = out.parent
        while pkg_dir != OUT_DIR.parent:
            _write_init(pkg_dir / '__init__.py')
            pkg_dir = pkg_dir.parent

        out.write_text(code)
        generated.append(out)
        print(f'  wrote: {out.relative_to(REPO_ROOT)}')

    # Write top-level __init__.py that re-exports KbnRawDashboard for convenience.
    init_path = OUT_DIR / '__init__.py'
    init_path.write_text(
        GENERATED_HEADER
        + '"""KbnRaw* permissive view models for parsing real-world Kibana dashboard JSON."""\n\n'
        + 'from kb_dashboard_tools.decompile.kbn_raw_models.dashboard.view import KbnRawDashboard\n\n'
        + '__all__ = [\'KbnRawDashboard\']\n'
    )

    print(f'\nGenerated {len(generated)} files in {OUT_DIR.relative_to(REPO_ROOT)}')

    # Auto-format with ruff to ensure CI passes.
    # Order matters: run check --fix first (removes unused imports, etc.), then format
    # (fixes whitespace/blank lines after imports were removed). A second format pass
    # ensures files left by check --fix are also properly formatted.
    import subprocess
    tools_dir = REPO_ROOT / 'packages' / 'kb-dashboard-tools'

    ruff_check = subprocess.run(
        ['uv', 'run', 'ruff', 'check', '--fix', str(OUT_DIR)],
        cwd=tools_dir,
        capture_output=True,
        text=True,
    )
    if ruff_check.returncode == 0:
        print('ruff check --fix: OK')
    else:
        print(f'ruff check --fix output: {ruff_check.stdout[:500]}')

    # Run format AFTER check --fix so any whitespace/blank-line changes from import removal
    # are normalized.
    ruff_result = subprocess.run(
        ['uv', 'run', 'ruff', 'format', str(OUT_DIR)],
        cwd=tools_dir,
        capture_output=True,
        text=True,
    )
    if ruff_result.returncode == 0:
        print('ruff format: OK')
    else:
        print(f'ruff format warning: {ruff_result.stderr}')


